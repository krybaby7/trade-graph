"""The synthetic OKX-format fixture (T29): generated here, committed under ``tests/fixtures/okx``, labelled synthetic.

okx.com could not be reached from the cloud build on 2026-10-16, so no real OKX response could be recorded. These
pages copy the response format of OKX's public ``history-candles`` endpoint as documented (newest first, decimal text,
``confirm`` "0" for the forming candle) with made-up SOL-USDT prices. They are test data, not market data. Step L2
records a real folder with ``trade-graph candles-okx-fetch --record``.

Integer arithmetic only, so every platform writes the same bytes; ``test_okx_candles`` checks the committed files
against ``fixture_files()``.
"""

from __future__ import annotations

import json
from datetime import UTC, datetime
from decimal import Decimal
from pathlib import Path

FIXTURE = Path(__file__).resolve().parent / "fixtures" / "okx" / "history_candles_SOL-USDT_15m_synthetic"
INST_ID = "SOL-USDT"
START = datetime(2026, 7, 1, tzinfo=UTC)
COMMITTED = 600  # 6.25 days of 15-minute candles, plus one still forming
STEP_MS = 15 * 60_000
PAGE = 100
_MASK = (1 << 64) - 1


class _Lcg:
    def __init__(self, seed: int) -> None:
        self.state = seed & _MASK

    def step(self, bound: int) -> int:
        self.state = (self.state * 6364136223846793005 + 1442695040888963407) & _MASK
        return (self.state >> 33) % bound


def rows() -> list[list[str]]:
    """Oldest first: a price around 150 USDT swinging on a 2-day wave, in cents; volume in SOL to 4 places."""
    rng = _Lcg(20261016)
    price = 15_000
    start_ms = int(START.timestamp()) * 1000
    result: list[list[str]] = []
    for index in range(COMMITTED + 1):
        phase = index % 192
        target = 15_000 + ((phase if phase < 96 else 192 - phase) - 48) * 10
        move = (target - price) * 8 // 100 + rng.step(121) - 60
        opened, closed = price, max(100, price + move)
        high = max(opened, closed) + rng.step(40)
        low = min(opened, closed) - rng.step(40)
        volume = Decimal(500_000 + rng.step(3_000_000)).scaleb(-4)
        quote = (volume * Decimal(closed).scaleb(-2)).quantize(Decimal("0.0001"))
        cents = [str(Decimal(value).scaleb(-2)) for value in (opened, high, low, closed)]
        confirm = "0" if index == COMMITTED else "1"
        result.append([str(start_ms + index * STEP_MS), *cents, str(volume), str(quote), str(quote), confirm])
        price = closed
    return result


def pages() -> list[str]:
    """Newest first, 100 rows a page, as OKX pages back with ``after``."""
    newest_first = list(reversed(rows()))
    return [json.dumps({"code": "0", "msg": "", "data": newest_first[start:start + PAGE]}, separators=(",", ":"))
            for start in range(0, len(newest_first), PAGE)]


def fixture_files() -> dict[str, str]:
    texts = pages()
    entries = []
    after = None
    for number, text in enumerate(texts, start=1):
        data = json.loads(text)["data"]
        query = f"instId={INST_ID}&bar=15m&limit=100" + ("" if after is None else f"&after={after}")
        entries.append({"file": f"page-{number:03d}.json",
                        "url": f"https://www.okx.com/api/v5/market/history-candles?{query}", "rows": len(data)})
        after = data[-1][0]
    manifest = {
        "format": "okx-history-candles-recording-v1", "evidence_label": "synthetic_fixture", "inst_id": INST_ID,
        "bar": "15m", "pages": entries,
        "note": ("Synthetic: generated by tests/okx_support.py in the documented OKX history-candles response format. "
                 "Not market data. Record a real folder at step L2 with candles-okx-fetch --record."),
    }
    files = {"manifest.json": json.dumps(manifest, indent=2) + "\n"}
    files.update({entry["file"]: text + "\n" for entry, text in zip(entries, texts, strict=True)})
    return files


if __name__ == "__main__":  # regenerate: uv run python -m tests.okx_support
    FIXTURE.mkdir(parents=True, exist_ok=True)
    for name, text in fixture_files().items():
        (FIXTURE / name).write_text(text, encoding="utf-8")
